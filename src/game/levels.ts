export function isRegionUnlocked(
  regionId: MapRegionId,
  highestLevelUnlocked: number,
  _unlockedRegions?: Record<MapRegionId, boolean>
): boolean {
  if (regionId === 'dhaka') return true;
  const def = REGIONS[regionId];
  return highestLevelUnlocked >= def.startLevel;
}

export function purchaseRegionAccess(
  arg1: MapRegionId | number,
  arg2: MapRegionId | number,
  customUnlockedRegions?: Record<MapRegionId, boolean>
): {
  success: boolean;
  remainingCoins: number;
  updatedRegions: Record<MapRegionId, boolean>;
  error?: string;
} {
  const coins: number = typeof arg1 === 'number' ? arg1 : (arg2 as number);
  const current = customUnlockedRegions || loadUnlockedRegions();

  return {
    success: false,
    remainingCoins: coins,
    updatedRegions: current,
    error: 'Buying levels or regions with coins is disabled. Clear previous sectors to unlock.',
  };
}

